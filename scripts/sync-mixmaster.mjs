// Generates data.js from the live Apps Script endpoints.
//
// The app used to fetch ~460 KB from Apps Script on every launch, so a cold start
// waited on a Google round-trip and offline showed nothing. data.js ships the
// catalogue with the app; the endpoints stay as a fallback and as the source of truth.
//
// Run after changing the spreadsheet:  node scripts/sync-mixmaster.mjs
// Never hand-edit data.js — regenerate it.

import { writeFileSync } from 'node:fs';

const BASE = 'https://script.google.com/macros/s/AKfycbwo8yV8kY20USsHptW_Mvd8wNXI_jBoOLtq6UI58ys7O9SgxxbAnMAeDrrWaEwriMS2/exec';
const SOURCES = {
  cocktails: `${BASE}?gid=2075268599`,
  mocktails: `${BASE}?gid=116292126`,
};

async function fetchList(name, url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  const data = await res.json();
  if (!Array.isArray(data) || !data.length) throw new Error(`${name}: empty or not an array`);
  return data;
}

const out = {};
for (const [name, url] of Object.entries(SOURCES)) {
  const list = await fetchList(name, url);
  const named = list.filter(item => item && item.name);
  const withImage = named.filter(item => String(item.image || '').startsWith('http'));
  console.log(`${name}: ${list.length} rows, ${named.length} named, ${withImage.length} with image`);
  if (named.length < list.length) console.warn(`  ⚠ ${list.length - named.length} row(s) without a name`);
  out[name] = named;
}

const banner = `// Generated by scripts/sync-mixmaster.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n`;
writeFileSync('data.js', `${banner}window.MIXMASTER_DATA = ${JSON.stringify(out)};\n`);

const kb = Math.round(Buffer.byteLength(JSON.stringify(out)) / 1024);
console.log(`\n✅ data.js written — cocktails: ${out.cocktails.length}, mocktails: ${out.mocktails.length} (${kb} KB)`);
